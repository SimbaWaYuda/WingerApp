      case 'es':
        return 'Español';
      case 'sw':
        return 'Kiswahili';
      default:
        return 'English';
    }
  }
}

class WingerStringsDelegate extends LocalizationsDelegate<WingerStrings> {
  const WingerStringsDelegate();

  @override
  bool isSupported(Locale locale) =>
      WingerStrings.supported.any((l) => l.languageCode == locale.languageCode);

  @override
  Future<WingerStrings> load(Locale locale) async => WingerStrings(locale);

  @override
  bool shouldReload(covariant LocalizationsDelegate<WingerStrings> old) => false;
}
